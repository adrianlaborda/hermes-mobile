#!/usr/bin/env python3
"""Regenerate the app's built-in themes from Hermes Desktop's source.

Hermes Desktop defines its palettes in `apps/shared/src/theme-presets.ts` (labels in
`apps/desktop/src/themes/presets.ts`). This script downloads both from a hermes-agent ref,
evaluates the presets with Node (so helper calls and constants resolve exactly as Desktop
resolves them), flattens `color-mix()` values the way Desktop paints them, and writes
`app/src/main/java/com/nousresearch/hermesmobile/ui/theme/DesktopThemePresets.kt`.

Usage: scripts/sync_desktop_themes.py [REF]   (default: main; needs `node` and `gh` or network)
"""
import json
import re
import subprocess
import sys
import tempfile
import urllib.request
from pathlib import Path

REF = sys.argv[1] if len(sys.argv) > 1 else "main"
RAW = "https://raw.githubusercontent.com/NousResearch/hermes-agent/{ref}/{path}"
ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "app/src/main/java/com/nousresearch/hermesmobile/ui/theme/DesktopThemePresets.kt"
FIELDS = ["background", "foreground", "card", "muted", "mutedForeground", "popover", "primary", "primaryForeground",
          "secondary", "accent", "border", "destructive", "sidebarBackground", "userBubble", "userBubbleBorder"]
MIX = re.compile(r"color-mix\(in srgb,\s*(#[0-9a-fA-F]{6})\s+([\d.]+)%,\s*(#[0-9a-fA-F]{6}|transparent)\s*\)")


def fetch(path: str) -> str:
    with urllib.request.urlopen(RAW.format(ref=REF, path=path), timeout=30) as r:
        return r.read().decode()


def rgb(h: str) -> tuple[int, int, int]:
    h = h.lstrip("#")
    return int(h[0:2], 16), int(h[2:4], 16), int(h[4:6], 16)


def hexa(c) -> str:
    return "#" + "".join(f"{max(0, min(255, round(v))):02x}" for v in c)


def flatten(value: str, backdrop: str) -> str:
    """A hex, or `color-mix(in srgb, A p%, B|transparent)` painted over the palette background."""
    value = value.strip()
    if re.fullmatch(r"#[0-9a-fA-F]{6}", value):
        return value.lower()
    m = MIX.fullmatch(value)
    if not m:
        raise SystemExit(f"unsupported color value: {value}")
    a, pct, b = rgb(m[1]), float(m[2]) / 100, m[3]
    other = rgb(backdrop) if b == "transparent" else rgb(b)
    return hexa(tuple(a[i] * pct + other[i] * (1 - pct) for i in range(3)))


def palette(colors: dict) -> dict:
    bg = flatten(colors["background"], "#000000")
    out = {"background": bg}
    for f in FIELDS[1:]:
        if f in colors:
            out[f] = flatten(colors[f], bg)
    # Desktop's fallbacks for the optional fields.
    out.setdefault("sidebarBackground", out["card"])
    out.setdefault("userBubble", out["secondary"])
    out.setdefault("userBubbleBorder", out["border"])
    return out


def kotlin_palette(p: dict) -> str:
    args = ", ".join(f"{f} = 0xFF{p[f][1:].upper()}" for f in FIELDS)
    return f"ThemePalette.of({args})"


def main() -> None:
    with tempfile.TemporaryDirectory() as tmp:
        presets_ts = Path(tmp, "theme-presets.ts")
        presets_ts.write_text(fetch("apps/shared/src/theme-presets.ts"))
        dump = Path(tmp, "dump.mjs")
        dump.write_text("const m = await import(process.argv[2]); console.log(JSON.stringify(m.THEME_PRESET_PALETTES))")
        palettes = json.loads(subprocess.run(["node", str(dump), str(presets_ts)], check=True, capture_output=True, text=True).stdout)
    labels = dict(re.findall(r"name: '([a-z-]+)',\s*\n\s*label: '([^']+)'", fetch("apps/desktop/src/themes/presets.ts")))

    entries = []
    for name, data in palettes.items():
        light = palette(data["colors"])
        dark = palette(data["darkColors"]) if data.get("darkColors") else None
        label = labels.get(name, name.replace("-", " ").title())
        entries.append(f'    "{name}" to DesktopTheme("{name}", "{label}",\n'
                       f'        {kotlin_palette(light)},\n'
                       f'        {kotlin_palette(dark) if dark else "null"}),')

    OUT.write_text(f'''package com.nousresearch.hermesmobile.ui.theme

// GENERATED by scripts/sync_desktop_themes.py from NousResearch/hermes-agent@{REF}
// (apps/shared/src/theme-presets.ts). Do not edit by hand: re-run the script.

/** Hermes Desktop's palette-bearing built-in themes, in Desktop's palette order. */
internal val DESKTOP_PRESET_PALETTES: Map<String, DesktopTheme> = linkedMapOf(
{chr(10).join(entries)}
)
''')
    print(f"wrote {OUT.relative_to(ROOT)}: {', '.join(palettes)}")


if __name__ == "__main__":
    main()
